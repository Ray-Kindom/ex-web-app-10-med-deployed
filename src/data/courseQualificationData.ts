export const inferCourseType = (
  def: Partial<CourseDefinition>,
  typeOverrides?: Record<string, CourseOrCadreType>
): CourseOrCadreType => {
  if (def.id && typeOverrides?.[def.id]) return typeOverrides[def.id];
  if (def.type === 'course' || def.type === 'cadre') return def.type;
  if (def.id) {
    if (KNOWN_CADRE_IDS.has(def.id) || def.id.startsWith('cadre_')) return 'cadre';
    if (KNOWN_COURSE_IDS.has(def.id)) return 'course';
  }
  const text = `${def.name || ''} ${def.bengaliName || ''} ${def.shortCode || ''}`.toLowerCase();
  if (text.includes('course') || text.includes('কোর্স')) return 'course';
  if (text.includes('cadre') || text.includes('cdr') || text.includes('ক্যাডার')) return 'cadre';
  return 'course';
};

