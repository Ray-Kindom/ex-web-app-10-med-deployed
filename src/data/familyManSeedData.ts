export function buildBanglaTitleFromPersonnel(p: Pick<Personnel, 'snkNo' | 'rk' | 'trade' | 'name'>): string {
  const bnNo = toBanglaDigits((p.snkNo || '').replace(/^BJO-/i, 'বিজেও-'));
  const bnRk = RANK_TO_BANGLA[p.rk] || p.rk;
  const bnTrade = p.trade && TRADE_TO_BANGLA[p.trade] !== undefined
    ? TRADE_TO_BANGLA[p.trade]
    : p.trade && p.trade !== '-'
    ? `(${p.trade})`
    : '';
  return [bnNo, bnRk, bnTrade, p.name].filter(Boolean).join(' ');
}

export function getBanglaBatteryName(battery?: string): string {
  switch (battery) {
    case 'HQ Bty':
      return 'হেডকোয়ার্টার ব্যাটারী';
    case 'P Bty':
      return 'পি ব্যাটারী';
    case 'Q Bty':
      return 'কিউ ব্যাটারী';
    case 'R Bty':
      return 'আর ব্যাটারী';
    default:
      return battery || '—';
  }
}

