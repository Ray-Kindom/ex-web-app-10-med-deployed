const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function toBanglaDigits(input: string | number): string {
  return String(input).replace(/\d/g, (d) => BN_DIGITS[Number(d)] ?? d);
}

/**
 * Formats ISO date 'YYYY-MM-DD' into Bengali short format 'DD-MM-YY' (e.g. '৩০-০৬-২৬')
 * matching the official register format. Non-ISO strings (e.g. 'সরকারী আবেদনের প্রেক্ষিতে')
 * are returned directly.
 */
export function formatIsoToBanglaShortDate(value?: string): string {
  if (!value || !value.trim()) return '';
  const trimmed = value.trim();
  const isoMatch = /^(\d{4})-(\d{2})-(\d{2})/.exec(trimmed);
  if (isoMatch) {
    const [, yyyy, mm, dd] = isoMatch;
    const yy = yyyy.slice(-2);
    return toBanglaDigits(`${dd}-${mm}-${yy}`);
  }
  return toBanglaDigits(trimmed);
}

export interface RemainingDaysInfo {
  daysLeft: number | null;
  label: string;
  subLabel?: string;
  status: 'expired' | 'critical' | 'warning' | 'safe' | 'none';
}

export function getRemainingDaysInfo(expiryDate?: string): RemainingDaysInfo {
  if (!expiryDate || !expiryDate.trim()) {
    return {
      daysLeft: null,
      label: 'নির্ধারিত নয়',
      status: 'none',
    };
  }
  const isoMatch = /^(\d{4})-(\d{2})-(\d{2})/.exec(expiryDate.trim());
  const exp = isoMatch
    ? new Date(Number(isoMatch[1]), Number(isoMatch[2]) - 1, Number(isoMatch[3]))
    : new Date(expiryDate);

  if (Number.isNaN(exp.getTime())) {
    return {
      daysLeft: null,
      label: 'নির্ধারিত নয়',
      status: 'none',
    };
  }

  const today = new Date();
  today.setHours(0, 0, 0, 0);
  exp.setHours(0, 0, 0, 0);

  const diffDays = Math.ceil((exp.getTime() - today.getTime()) / 86400000);

  if (diffDays < 0) {
    return {
      daysLeft: diffDays,
      label: `মেয়াদ উত্তীর্ণ (${toBanglaDigits(Math.abs(diffDays))} দিন আগে)`,
      subLabel: 'খালির তারিখ অতিক্রান্ত',
      status: 'expired',
    };
  }
  if (diffDays === 0) {
    return {
      daysLeft: 0,
      label: 'আজ মেয়াদ শেষ',
      subLabel: 'অবিলম্বে নবায়ন/খালি',
      status: 'critical',
    };
  }
  if (diffDays <= 30) {
    return {
      daysLeft: diffDays,
      label: `${toBanglaDigits(diffDays)} দিন বাকি`,
      subLabel: 'জরুরি (৩০ দিনের কম)',
      status: 'critical',
    };
  }
  if (diffDays <= 90) {
    const months = Math.floor(diffDays / 30);
    const rem = diffDays % 30;
    return {
      daysLeft: diffDays,
      label: `${toBanglaDigits(diffDays)} দিন বাকি`,
      subLabel: months > 0 ? `প্রায় ${toBanglaDigits(months)} মাস ${toBanglaDigits(rem)} দিন` : undefined,
      status: 'warning',
    };
  }
  const months = Math.floor(diffDays / 30);
  const rem = diffDays % 30;
  return {
    daysLeft: diffDays,
    label: `${toBanglaDigits(diffDays)} দিন বাকি`,
    subLabel: `প্রায় ${toBanglaDigits(months)} মাস ${toBanglaDigits(rem)} দিন`,
    status: 'safe',
  };
}

export function inferRankCategory(rk?: string, banglaFullTitle?: string): FamilyManRankGroup {
  const rkUpper = (rk || '').toUpperCase().trim();
  const bn = banglaFullTitle || '';
  if (
    ['MWO', 'SWO', 'WO', 'JCO', 'H/LT', 'H/CAPT'].includes(rkUpper) ||
    bn.includes('বিজেও') ||
    bn.includes('ওয়াঃ অফিঃ')
  ) {
    return 'জেসিও';
  }
  if (rkUpper.includes('NC') || bn.includes('এনসি(ই)') || bn.includes('এনসি (ই)')) {
    return 'এনসি (ই)';
  }
  return 'অন্যান্য পদবী';
}

